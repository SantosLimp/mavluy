export function parseCityEntry(entry: string): { ar: string; fr: string } {
  const match = (entry || '').match(/^(.*?)\s*\((.*?)\)$/);
  if (match) {
    return { ar: match[1].trim(), fr: match[2].trim() };
  }
  return { ar: (entry || '').trim(), fr: (entry || '').trim() };
}

export function getCitiesForCountry(countrySlugOrCode: string = 'ma', lang: string = 'ar'): string[] {
  const clean = (countrySlugOrCode || 'ma').toLowerCase().trim();
  const rawList = COUNTRY_CITIES[clean] || COUNTRY_CITIES.ma || [];
  const isArabic = (lang || 'ar').toLowerCase().startsWith('ar');

  const mapped = rawList.map(entry => {
    const parsed = parseCityEntry(entry);
    return isArabic ? parsed.ar : parsed.fr;
  });

  return Array.from(new Set(mapped));
}

export function translateCity(cityName: string, targetLang: string = 'ar'): string {
  if (!cityName || !cityName.trim()) return '';
  const isArabic = (targetLang || 'ar').toLowerCase().startsWith('ar');
  const clean = cityName.trim();

  // If in format "الدار البيضاء (Casablanca)"
  const match = clean.match(/^(.*?)\s*\((.*?)\)$/);
  if (match) {
    return isArabic ? match[1].trim() : match[2].trim();
  }

  // Find matches across known city records
  for (const list of Object.values(COUNTRY_CITIES)) {
    for (const item of list) {
      const parsed = parseCityEntry(item);
      if (parsed.ar.toLowerCase() === clean.toLowerCase()) {
        return isArabic ? parsed.ar : parsed.fr;
      }
      if (parsed.fr.toLowerCase() === clean.toLowerCase()) {
        return isArabic ? parsed.ar : parsed.fr;
      }
    }
  }

  return clean;
}
